"""English-language coverage for judge-facing documentation and generated copy."""
import json
from pathlib import Path
import re

import pytest

ROOT=Path(__file__).resolve().parents[1]
SPANISH_COPY=re.compile(r'\b(?:auditoría|hallazgos|correcciones|verificación|muestreo|pruebas|revisión|cuentas|pendientes|cumplido|riesgos|recomendaciones|resultado|fuentes|sin resolver|no se|se ejecutó|se comprobó)\b',re.I)
DOCS=[ROOT/'README.md',*sorted((ROOT/'docs').glob('*.md')),*sorted((ROOT/'audit').glob('**/README.md')),*sorted((ROOT/'data/bigquery').glob('**/README.md'))]


@pytest.mark.parametrize('path',DOCS,ids=lambda path:str(path.relative_to(ROOT)))
def test_judge_facing_documentation_has_no_known_spanish_copy(path):
    # Keep identifiers, links and commands intact; these are not translated prose.
    prose=re.sub(r'```.*?```|`[^`]*`|\]\([^)]*\)', '', path.read_text(), flags=re.S)
    match=SPANISH_COPY.search(prose)
    assert match is None, f'{path.relative_to(ROOT)} contains untranslated copy: {match.group()}'


def test_generated_chart_results_and_narrative_are_english():
    def strings(value):
        if isinstance(value,str):yield value
        elif isinstance(value,dict):
            for v in value.values():yield from strings(v)
        elif isinstance(value,list):
            for v in value:yield from strings(v)
    spec=json.loads((ROOT/'site/data.json').read_text())
    failures=[text[:180] for text in strings(spec) if SPANISH_COPY.search(text)]
    assert not failures,failures
    assert '<html lang="en">' in (ROOT/'near_thesis/web/index.html').read_text()


def test_translated_document_relative_links_resolve():
    failures=[]
    for path in DOCS:
        for link in re.findall(r'\]\(([^)]+)\)',path.read_text()):
            target=link.split('#',1)[0]
            if not target or '://' in target or target.startswith(('mailto:','/')):continue
            if not (path.parent/target).exists():failures.append((str(path.relative_to(ROOT)),target))
    assert not failures,failures


def test_offline_review_documents_are_english_and_local_links_work(tmp_path):
    from html.parser import HTMLParser
    from urllib.parse import unquote,urlsplit
    from near_thesis import documentation
    class Links(HTMLParser):
        def __init__(self):
            super().__init__();self.links=[];self.text=[]
        def handle_starttag(self,tag,attrs):
            if tag=='a':self.links.extend(value for key,value in attrs if key=='href')
        def handle_data(self,value):self.text.append(value)
    documentation.run(tmp_path)
    # Dashboard is generated by site.run, outside this isolated documentation test.
    (tmp_path/'index.html').write_text('<html lang="en"></html>')
    pages=list(tmp_path.rglob('*.html'))
    expected={path.resolve() for path in DOCS}|{(ROOT/'THESIS.md').resolve()}
    assert len(pages)==len(expected)+1
    for page in pages:
        markup=page.read_text();assert '<html lang="en">' in markup,page
        parser=Links();parser.feed(markup)
        assert not SPANISH_COPY.search(' '.join(parser.text)),page
        for link in parser.links:
            parsed=urlsplit(link)
            if not parsed.scheme and parsed.path:
                assert (page.parent/unquote(parsed.path)).exists(),(page,link)
    thesis=(tmp_path/'THESIS.html').read_text()
    assert 'Current verdict:' in thesis
    assert 'Back to dashboard' in thesis


def test_document_renderer_escapes_raw_html_and_unsafe_urls(tmp_path,monkeypatch):
    from near_thesis import documentation
    source=tmp_path/'source';source.mkdir()
    for directory in ['docs','audit','data/bigquery','near_thesis/web']:(source/directory).mkdir(parents=True)
    (source/'near_thesis/web/review-docs.css').write_text('body { color: black; }')
    (source/'README.md').write_text('# Review\n<script>window.__bad=1</script>\n\n[Unsafe](javascript:alert%281%29)')
    (source/'THESIS.md').write_text('# Thesis\nEnglish evidence.')
    monkeypatch.setattr(documentation,'ROOT',source)
    documentation.run(tmp_path/'rendered')
    page=(tmp_path/'rendered/README.html').read_text()
    assert '<script>' not in page
    assert '&lt;script&gt;' in page
    assert 'href="javascript:' not in page
